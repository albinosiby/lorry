      }
      if ((argument == 0 &&
              const {
                '{0} · {1} t · {2} ft',
                '{0} • {1} body',
              }.contains(template.key)) ||
          (argument == 1 && template.key == '{0} · {1} · {2} t')) {
        value = translateUi(value, languageCode);
      }
      translated = translated.replaceAll('{$argument}', value);
    }
    return translated;
  }
  for (final greeting in ['Good morning', 'Good afternoon', 'Good evening']) {
    if (source.startsWith('$greeting,')) {
      return '${translateUi(greeting, languageCode)}${source.substring(greeting.length)}';
    }
  }
  return source;
}
